-- TABLA.
CREATE TABLE FACTORIZACIONES (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    COEF_A NUMBER NOT NULL,
    COEF_B NUMBER NOT NULL,
    COEF_C NUMBER NOT NULL,
    ECUACION VARCHAR2(500) NOT NULL,
    RESULTADO VARCHAR2(1000) NOT NULL,
    FECHA_REGISTRO TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

COMMIT;

-- CONSULTAR HISTORIAL.
SELECT ID, COEF_A, COEF_B, COEF_C, ECUACION, RESULTADO, FECHA_REGISTRO
FROM FACTORIZACIONES ORDER BY ID DESC;  